// Real renderer/backend; all catalog entries, profiles and files are disposable.
const { app, BrowserWindow, ipcMain, protocol, net } = require('electron');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { spawn } = require('node:child_process');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
const { appAsset, APP_HEADERS, trustedUrl } = require('../electron/security');
const { registerLibraryDownloadIpc } = require('../electron/libraryDownloads');
const root = path.resolve(__dirname, '..');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'law-image-folders-'));
app.setPath('userData', path.join(work, 'profile'));
protocol.registerSchemesAsPrivileged([{ scheme: 'app', privileges: { standard: true, secure: true, supportFetchAPI: true } }]);
let win, child;
const checks = [];
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn, label) {
  const end = Date.now() + 30000;
  while (Date.now() < end) { if (await fn()) return; await pause(80); }
  throw Error('Timed out: ' + label);
}
app.whenReady().then(async () => {
  child = spawn(path.join(root, 'venv/Scripts/python.exe'), [path.join(root, 'scripts/qa-image-manager-fixture.py'), work], { cwd: root, windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'], env: { ...process.env, LAW_QA_IMAGE_SCAN_GATE: '1' } });
  let stderr = '';
  child.stderr.on('data', data => { stderr += data; });
  const connection = await new Promise((resolve, reject) => {
    let text = '';
    const timer = setTimeout(() => reject(Error('Fixture startup failed: ' + stderr.slice(-1500))), 30000);
    child.stdout.on('data', data => { text += data; if (text.includes('\n')) { clearTimeout(timer); resolve(JSON.parse(text.split('\n')[0])); } });
    child.once('error', reject);
  });
  protocol.handle('app', async request => {
    const response = await net.fetch(pathToFileURL(appAsset(path.join(root, process.env.LAW_QA_IMAGE_BUILD || 'dist'), request.url)).toString());
    return new Response(response.body, { headers: { ...Object.fromEntries(response.headers), ...APP_HEADERS } });
  });
  win = new BrowserWindow({ show: false, width: 1200, height: 950, webPreferences: { preload: path.join(root, 'electron/preload.js'), contextIsolation: true, nodeIntegration: false, offscreen: true, backgroundThrottling: false } });
  ipcMain.on('app:connection', event => { event.returnValue = event.sender === win.webContents ? connection : null; });
  registerLibraryDownloadIpc({ ipcMain, trustedDesktop: event => event.sender === win.webContents && event.senderFrame === event.sender.mainFrame && trustedUrl(event.senderFrame.url), getConnection: () => connection });
  ipcMain.handle('app:startup-status', () => ({ state: 'ready' }));
  ipcMain.handle('app:capabilities', () => ({ features: {} }));
  for (const name of ['media-manager:place', 'viewer-browser:place', 'linked-content:place']) ipcMain.handle(name, () => {});
  ipcMain.handle('maintenance:import-status', () => ({ active: false }));
  ipcMain.handle('github-publication:state', () => ({ status: 'idle' }));
  ipcMain.handle('function-workflows:state', () => null);
  ipcMain.handle('sound-mixer:configure', () => ({ ok: true }));
  ipcMain.handle('image-manager:choose-folder', (_event, purpose) => ({ path: path.join(work, purpose === 'source' ? 'image-source' : 'image-output') }));
  const js = code => win.webContents.executeJavaScript(code).catch(error => { throw new Error(`Image Manager QA failed: ${code}: ${error.message}`); });
  const reload = async () => {
    const loaded = new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    await js("document.querySelector('.workspace-refresh').click()");
    await loaded;
    await until(() => js("document.querySelector('[data-capture-tab=image-manager]')?.hidden===false"), 'manager visible after refresh');
  };
  const click = async (text, scope = '.image-manager') => {
    const find = `(()=>[...(document.querySelector(${JSON.stringify(scope)})?.querySelectorAll('button') || [])].find(b=>b.textContent.trim()===${JSON.stringify(text)}))()`;
    await until(() => js(`!!${find} && !${find}.disabled`), text);
    await js(`${find}.click()`);
  };
  const select = (label, value) => js(`(()=>{const e=document.querySelector('select[aria-label=${JSON.stringify(label)}]');e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const api = async (route, method = 'GET', body) => {
    const response = await fetch(connection.base + '/image-manager' + route, { method, headers: { 'X-LAW-Session': connection.token, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    const value = await response.json(); assert(response.ok, JSON.stringify(value)); return value;
  };
  const task = async (kind, payload) => {
    const { job_id } = await api('/tasks', 'POST', { kind, ...payload });
    await until(async () => { const job = (await api('/state')).job; return job?.id === job_id && job.status !== 'running'; }, kind);
    const job = (await api('/state')).job; assert.equal(job.status, 'complete', job.message); return job.result;
  };
  await win.loadURL('app://local/index.html');
  await until(() => js("!!document.querySelector('.image-manager')"), 'manager mount');
  await js("document.querySelector('[data-sidebar-route=image-manager]').click()");
  await until(() => js("document.querySelector('[data-capture-tab=image-manager]')?.hidden===false"), 'manager visible');
  assert.equal(await js("document.querySelector('[aria-label=\"Filter image folder\"]').value"), '__none__');
  assert.equal((await api('/state')).job, null);
  await click('+ Add source folder'); await click('Choose output folder'); await click('Scan folders');
  await until(() => js("document.querySelectorAll('.im-grid article').length===3"), 'source thumbnails');
  let state = await api('/state');
  const output = state.folders.find(folder => folder.purpose === 'output');
  const other = await api('/folders', 'POST', { path: path.join(work, 'scroll-source'), purpose: 'output' });
  const rows = (await api('/images')).images;
  const result = await task('plan', { ids: rows.map(row => row.id), output_id: output.id, layout: 'folders', mode: 'copy' });
  await task('apply', { plan_id: result.plan_id, confirmation: 'COPY 3' });
  const saved = fs.readdirSync(output.path).map(name => ({ path: path.join(output.path, name), bytes: fs.readFileSync(path.join(output.path, name)) }));
  await until(() => js("document.querySelectorAll('.im-folder-list > div').length===3"), 'all source/output rows');
  await js("document.querySelector('.im-folders').open=true");
  fs.writeFileSync(path.join(work, 'folders.png'), (await win.webContents.capturePage()).toPNG());
  await select('Filter image folder', output.id);
  await until(() => js("document.querySelectorAll('.im-grid article').length===3"), 'output browsing');
  await click('Select page'); await select('Filter image folder', '__none__');
  await until(() => js("document.querySelectorAll('.im-grid article').length===0 && document.querySelector('.im-selection').textContent.includes('0 selected')"), 'clear browsing and selection');
  await click('Image tools');
  await until(() => js("document.querySelector('.im-tools-dialog')?.open"), 'tools open');
  assert.equal(await js("document.querySelector('[aria-label=\"Image tools source\"]').value"), '');
  await js("document.querySelector('.im-tools-dialog [aria-label=\"Close dialog\"]').click()");
  checks.push('Three saved folders are manageable; clearing browsing clears thumbnails/selection; Image tools stays unselected');
  const forgetOutput = () => js(`document.querySelector(${JSON.stringify(`button[aria-label=${JSON.stringify('Forget ' + output.path)}]`)}).click()`);
  await forgetOutput(); await click('Cancel', '.im-dialog');
  assert.equal((await api('/state')).folders.length, 3);
  await forgetOutput(); await click('Forget folder', '.im-dialog');
  await until(async () => (await api('/state')).folders.length === 2, 'output forgotten');
  assert((await api('/state')).folders.some(folder => folder.id === other.id));
  assert.equal((await api('/images?folder_id=' + output.id)).total, 0);
  for (const file of saved) assert.deepEqual(fs.readFileSync(file.path), file.bytes);
  checks.push('Forget output: Cancel preserves catalog; confirmation removes only its entries and preserves every output file byte');
  await reload();
  await until(() => js("!!document.querySelector('[aria-label=\"Filter image folder\"]')"), 'reload');
  assert.equal(await js("document.querySelector('[aria-label=\"Filter image folder\"]').value"), '__none__');
  const source = (await api('/state')).folders.find(folder => folder.purpose === 'source');
  await until(() => js(`!!document.querySelector('[aria-label="Filter image folder"] option[value="${source.id}"]')`), 'source folder loaded after refresh');
  await select('Filter image folder', source.id);
  await until(() => js("document.querySelectorAll('.im-grid article').length===3"), 'source before rescan');
  fs.copyFileSync(path.join(source.path, 'landscape.png'), path.join(source.path, 'new-image.png'));
  const gate = path.join(work, 'pause-scan');
  fs.writeFileSync(gate, 'hold synthetic scan for renderer reload');
  const { job_id: scanId } = await api('/tasks', 'POST', { kind: 'scan', folder_ids: [source.id] });
  await until(() => fs.existsSync(path.join(work, 'scan-paused')), 'scan paused inside metadata read');
  await until(() => js("!![...document.querySelectorAll('.im-job button')].find(b=>b.textContent==='Stop task')"), 'running scan displayed');
  await reload();
  await until(() => js(`document.querySelector('[aria-label="Filter image folder"]')?.value===${JSON.stringify(source.id)} && document.querySelectorAll('.im-grid article').length===3`), 'restored source images during scan');
  assert.equal((await api('/state')).job.id, scanId);
  assert.equal((await api('/state')).job.status, 'running');
  assert.equal(await js("document.querySelector('.im-selection').textContent.includes('0 selected')"), true);
  fs.unlinkSync(gate);
  await until(() => js("document.querySelectorAll('.im-grid article').length===4"), 'new image after rescan');
  assert.equal((await api('/state')).job.id, scanId);
  assert.equal((await api('/state')).job.status, 'complete');
  checks.push('Refresh during a real backend scan restores the browsed folder and images, keeps the same job, and displays its new result');
  await task('scan', { folder_ids: [other.id] });
  await select('Filter image folder', other.id); await select('Sort images', 'name');
  await until(() => js("document.querySelectorAll('.im-grid article').length===48"), 'paged folder');
  const originals = fs.readdirSync(other.path).map(name => ({ path: path.join(other.path, name), bytes: fs.readFileSync(path.join(other.path, name)), mtime: fs.statSync(path.join(other.path, name)).mtimeMs }));
  await js("document.querySelector('[aria-label=\"Preview image-047.png\"]').click()");
  await until(() => js("!!document.querySelector('.im-image-preview [aria-label=\"Next image\"]')"), 'preview controls');
  await js("document.querySelector('.im-image-preview [aria-label=\"Next image\"]').click()");
  await until(() => js("document.querySelector('.im-image-preview')?.getAttribute('aria-label')==='image-048.png'"), 'preview across page boundary');
  assert.match(await js("document.querySelector('.im-image-preview').textContent"), /49 of 52/);
  await js("document.querySelector('.im-image-preview [aria-label=\"Close dialog\"]').click()");
  await click('Previous');
  await until(() => js("!!document.querySelector('[aria-label=\"Preview image-000.png\"]')"), 'first page');
  await js("document.querySelector('[aria-label=\"Preview image-000.png\"]').click()");
  await until(() => js("!!document.querySelector('.im-image-preview[open]')"), 'first preview');
  await js("document.querySelector('.im-image-preview').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true}))");
  await until(() => js("document.querySelector('.im-image-preview')?.getAttribute('aria-label')==='image-051.png'"), 'keyboard wraps to last matching image');
  await until(() => js("document.querySelector('.im-image-preview img')?.naturalWidth>0"), 'real preview image');
  fs.writeFileSync(path.join(work, 'navigation.png'), (await win.webContents.capturePage()).toPNG());
  await js("document.querySelector('.im-image-preview [aria-label=\"Add image-051.png to stitcher\"]').click()");
  await js("document.querySelector('.im-image-preview [aria-label=\"Previous image\"]').click()");
  await until(() => js("document.querySelector('.im-image-preview')?.getAttribute('aria-label')==='image-050.png'"), 'adjacent frame');
  await js("document.querySelector('.im-image-preview [aria-label=\"Add image-050.png to stitcher\"]').click()");
  await click('Preview stitch', '.im-image-preview');
  await until(() => js("document.querySelector('.image-stitcher-dialog .stitch-preview img')?.naturalWidth>0"), 'real catalog stitch preview');
  assert.deepEqual(await js("[...document.querySelectorAll('.image-stitcher-dialog .stitch-frame-name')].map(node=>node.textContent)"), ['1. image-051.png', '2. image-050.png']);
  await click('Save stitched image', '.image-stitcher-dialog');
  await until(() => js("document.querySelector('.image-stitcher-dialog footer').textContent.includes('Saved in Saved Images')"), 'stitch saved');
  let downloaded;
  win.webContents.session.once('will-download', (_event, item) => { item.setSavePath(path.join(work, 'stitched.png')); item.once('done', (_event, status) => { downloaded = status; }); });
  await click('Download PNG', '.image-stitcher-dialog');
  await until(() => downloaded, 'PNG download'); assert.equal(downloaded, 'completed');
  assert(trustedUrl(win.webContents.getURL()));
  const listing = await (await fetch(connection.base + '/image-library', { headers: { 'X-LAW-Session': connection.token } })).json();
  const composite = listing.images.find(item => item.origin.kind === 'stitch');
  assert(composite); assert.equal(composite.origin.sources.every(item => item.kind === 'managed'), true);
  const content = await fetch(connection.base + composite.url, { headers: { 'X-LAW-Session': connection.token } });
  assert.deepEqual(fs.readFileSync(path.join(work, 'stitched.png')), Buffer.from(await content.arrayBuffer()));
  for (const file of originals) { assert.deepEqual(fs.readFileSync(file.path), file.bytes); assert.equal(fs.statSync(file.path).mtimeMs, file.mtime); }
  fs.writeFileSync(path.join(work, 'stitcher.png'), (await win.webContents.capturePage()).toPNG());
  await click('Keep browsing', '.image-stitcher-dialog');
  win.setSize(640, 900);
  await js("document.querySelector('[aria-label=\"Preview image-050.png\"]').click()");
  await until(() => js("!!document.querySelector('.im-image-preview[open]')"), 'narrow preview');
  assert.equal(await js("(()=>{const dialog=document.querySelector('.im-image-preview'),bounds=dialog.getBoundingClientRect();return bounds.left>=0 && bounds.right<=innerWidth && dialog.scrollWidth<=dialog.clientWidth;})()"), true);
  win.webContents.invalidate(); await pause(200);
  fs.writeFileSync(path.join(work, 'navigation-narrow.png'), (await win.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG());
  await js("document.querySelector('.im-image-preview [aria-label=\"Close dialog\"]').click()");
  checks.push('Filtered preview crosses pages and wraps by keyboard; ordered catalog frames preview, save and download through the shared stitcher with originals unchanged');
  fs.writeFileSync(path.join(work, 'result.json'), JSON.stringify({ ok: true, checks }, null, 2));
  console.log(JSON.stringify({ ok: true, checks, work }));
}).catch(error => { console.error(error.stack); process.exitCode = 1; }).finally(() => { if (child) child.kill(); if (win && !win.isDestroyed()) win.destroy(); app.exit(process.exitCode || 0); });

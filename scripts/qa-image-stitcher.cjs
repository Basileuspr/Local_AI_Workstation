// Real Chromium, gallery components and API in an isolated profile with synthetic images.
const { app, BrowserWindow, protocol, ipcMain } = require('electron');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), net = require('node:net');
const { spawn } = require('node:child_process'), assert = require('node:assert/strict');
const { appAsset, APP_HEADERS, trustedUrl } = require('../electron/security');
const { registerLibraryDownloadIpc } = require('../electron/libraryDownloads');
const root = path.resolve(__dirname, '..'), work = fs.mkdtempSync(path.join(os.tmpdir(), 'law-stitcher-qa-'));
app.setPath('userData', path.join(work, 'profile'));
// The fixture needs 2D DOM rendering only; avoid competing with live GPU jobs.
app.disableHardwareAcceleration();
protocol.registerSchemesAsPrivileged([{ scheme: 'app', privileges: { standard: true, secure: true, supportFetchAPI: true } }]);
let win, backend, status = 0;
const errors = [], sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const guard = setTimeout(() => { backend?.kill(); app.exit(1); }, 120000);
app.whenReady().then(async () => {
  const [{ build }, { default: react }] = await Promise.all([import('vite'), import('@vitejs/plugin-react')]);
  const buildDir = path.join(work, 'build');
  await build({ configFile: false, root, plugins: [react()], base: './', build: { outDir: buildDir, emptyOutDir: true, rollupOptions: { input: path.join(root, 'tests/fixtures/imageStitcher.html') } } });
  const port = await new Promise(resolve => { const server = net.createServer(); server.listen(0, '127.0.0.1', () => { const port = server.address().port; server.close(() => resolve(port)); }); });
  const base = `http://127.0.0.1:${port}`;
  backend = spawn(path.join(root, 'venv/Scripts/python.exe'), ['-B', '-m', 'uvicorn', 'imageStitcher_backend:app', '--app-dir', 'tests/fixtures', '--host', '127.0.0.1', '--port', String(port)], { cwd: root, windowsHide: true, env: { ...process.env, PYTHONPATH: path.join(root, 'backend'), LAW_DATA_DIR: path.join(work, 'data'), LAW_MODELS_DIR: path.join(work, 'models'), LAW_LOG_DIR: path.join(work, 'logs') } });
  let log = ''; backend.stderr.on('data', data => log += data);
  for (let i = 0; ; i++) { try { if ((await fetch(base + '/image-library')).ok) break; } catch {} if (i >= 300) throw Error(log); await sleep(50); }
  protocol.handle('app', request => { const file = appAsset(buildDir, request.url); return new Response(fs.readFileSync(file), { headers: { ...APP_HEADERS, 'Content-Type': ({ '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' }[path.extname(file)] || 'application/octet-stream') } }); });
  const trustedDesktop = event => event.sender === win?.webContents && event.senderFrame === event.sender.mainFrame && trustedUrl(event.senderFrame.url);
  ipcMain.on('app:connection', event => { event.returnValue = trustedDesktop(event) ? { base, token: '' } : null; });
  let saveName = 'stitched.png'; const externalActions = [];
  registerLibraryDownloadIpc({ ipcMain, trustedDesktop, getConnection: () => ({ base, token: '' }), downloads: () => work,
    showDialog: async () => ({ filePath: path.join(work, saveName) }),
    shell: { showItemInFolder: file => externalActions.push(['reveal', file]), openPath: async file => { externalActions.push(['open', file]); return ''; } } });
  win = new BrowserWindow({ show: false, width: 1360, height: 1000, webPreferences: { preload: path.join(root, 'electron/preload.js'), offscreen: true, sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } });
  win.webContents.on('will-navigate', (event, url) => { if (!trustedUrl(url)) event.preventDefault(); });
  win.webContents.on('will-frame-navigate', event => { if (!trustedUrl(event.url)) event.preventDefault(); });
  win.webContents.on('console-message', event => { if (event.level === 'error' || event.level === 3) errors.push(event.message); });
  const js = code => win.webContents.executeJavaScript(code);
  const until = async (code, label) => { for (let i = 0; i < 200; i++) { if (await js(code)) return; await sleep(50); } throw Error(label + '\n' + await js('document.body.innerText')); };
  const click = async selector => { await until(`!!document.querySelector(${JSON.stringify(selector)}) && !document.querySelector(${JSON.stringify(selector)}).disabled`, selector); await js(`document.querySelector(${JSON.stringify(selector)}).click()`); await sleep(80); };
  const textClick = async text => { const expression = `[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)})`; await until(`!!(${expression}) && !(${expression}).disabled`, text); await js(`(${expression}).click()`); await sleep(80); };
  const set = async (selector, value) => { await js(`(()=>{const field=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(field instanceof HTMLSelectElement?HTMLSelectElement.prototype:HTMLInputElement.prototype,'value').set.call(field,${JSON.stringify(value)});field.dispatchEvent(new Event(field instanceof HTMLSelectElement?'change':'input',{bubbles:true}));})()`); await sleep(80); };
  const capture = async name => { win.webContents.invalidate(); await sleep(200); fs.writeFileSync(path.join(work, name), (await win.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG()); };
  const trayNames = () => js("[...document.querySelectorAll('.image-stitcher-tray .stitch-frame-name')].map(n=>n.textContent)");
  await win.loadURL(`app://local/tests/fixtures/imageStitcher.html?apiPort=${port}`);
  await until("document.querySelectorAll('.gallery-item').length===36", 'gallery');
  await click('[title="Enlarge Scene 01.png"]');
  await click('.image-viewer [aria-label="Add Scene 01.png to stitcher"]');
  await click('[aria-label="Next image"]'); await click('[aria-label="Next image"]');
  await click('.image-viewer [aria-label="Add Scene 03.png to stitcher"]');
  await click('[aria-label="Close image viewer"]');
  assert.deepEqual(await trayNames(), ['1. Scene 01.png', '2. Scene 03.png']);
  await click('[aria-label="Next images page"]');
  await click('[aria-label="Add Scene 38.png to stitcher"]');
  await set('[aria-label="Search image library"]', 'Scene 02');
  assert.equal((await trayNames()).length, 3);
  await textClick('Saved Images');
  await until("document.querySelectorAll('[aria-label=\"Saved Images\"] .gallery-item').length===36", 'saved collection');
  await click('[aria-label="Add Scene 04.png to stitcher"]');
  await click('[aria-label="Move frame 4 earlier"]');
  await click('[aria-label="Remove frame 4"]');
  assert.deepEqual(await trayNames(), ['1. Scene 01.png', '2. Scene 03.png', '3. Scene 04.png']);
  await capture('gallery-tray.png');
  await textClick('Preview stitch');
  await until("document.querySelector('.stitch-preview img')?.naturalWidth>0", 'strip preview');
  await set('[aria-label="Stitch layout"]', 'grid');
  await set('[aria-label="Stitch columns"]', '2');
  await set('[aria-label="Stitch spacing"]', '8');
  await until("document.querySelector('.stitch-preview figcaption')?.textContent.includes('648 × 368') && document.querySelector('.stitch-preview img')?.naturalWidth>0", 'grid dimensions');
  await capture('stitch-preview.png');
  await textClick('Save stitched image');
  await until("document.querySelector('.image-stitcher-dialog footer')?.textContent.includes('Saved in Saved Images')", 'saved result');
  await textClick('Save image as…');
  await until("document.querySelector('.image-file-actions')?.textContent.includes('Open saved copy')", 'verified native save');
  await textClick('Open saved copy'); await textClick('Show saved copy in folder');
  assert.equal(externalActions.length, 2);
  assert(trustedUrl(win.webContents.getURL()), 'download must not navigate the renderer');
  const result = await (await fetch(base + '/fixture/check')).json();
  assert.equal(result.originals_unchanged, true);
  assert.equal(result.stitches.length, 1);
  const saved = result.stitches[0];
  assert.deepEqual([saved.width, saved.height], [648, 368]);
  assert.equal(saved.origin.sources.length, 3);
  assert.deepEqual(fs.readFileSync(path.join(work, 'stitched.png')), Buffer.from(await (await fetch(base + saved.url)).arrayBuffer()));
  await textClick('Keep browsing');
  await textClick('Collapse stitcher');
  await textClick('Image stitcher (3)');
  assert.equal((await trayNames()).length, 3);
  const large = await (await fetch(base + '/fixture/large', { method: 'POST' })).json();
  await js("window.dispatchEvent(new Event('image-library-changed'))");
  await set('[aria-label="Search image library"]', 'Stitched-grid');
  await until(`!!document.querySelector('.gallery-item img[src*="${large.id}"]')`, 'large grid card');
  await js(`document.querySelector('.gallery-item img[src*="${large.id}"]').closest('button').click()`);
  await until("document.querySelector('.image-viewer .image-zoom img')?.naturalWidth===1600", 'scaled initial preview');
  await textClick('100%');
  await until("document.querySelector('.image-viewer .image-zoom img')?.naturalWidth===6144", 'full-resolution original');
  assert.equal(await js("document.querySelector('.image-viewer [aria-label=\"Image zoom\"]').textContent"), '100%');
  const transformBefore = await js("document.querySelector('.image-viewer .image-zoom img').style.transform");
  await js("(()=>{const view=document.querySelector('.image-viewer .image-zoom-viewport');view.focus();view.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));})()");
  await sleep(100);
  assert.notEqual(await js("document.querySelector('.image-viewer .image-zoom img').style.transform"), transformBefore);
  const dragPoint = await js("(()=>{const r=document.querySelector('.image-viewer .image-zoom-viewport').getBoundingClientRect();return {x:Math.round(r.left+r.width/2),y:Math.round(r.top+r.height/2)};})()");
  const beforeDrag = await js("document.querySelector('.image-viewer .image-zoom img').style.transform");
  win.webContents.sendInputEvent({ type: 'mouseDown', ...dragPoint, button: 'left', clickCount: 1 });
  win.webContents.sendInputEvent({ type: 'mouseMove', x: dragPoint.x + 100, y: dragPoint.y + 40 });
  win.webContents.sendInputEvent({ type: 'mouseUp', x: dragPoint.x + 100, y: dragPoint.y + 40, button: 'left', clickCount: 1 });
  await sleep(100);
  assert.notEqual(await js("document.querySelector('.image-viewer .image-zoom img').style.transform"), beforeDrag);
  await js("(()=>{const view=document.querySelector('.image-viewer .image-zoom-viewport'),r=view.getBoundingClientRect();view.dispatchEvent(new WheelEvent('wheel',{deltaY:-100,clientX:r.left+r.width/2,clientY:r.top+r.height/2,bubbles:true,cancelable:true}));})()");
  await sleep(100);
  assert(Number.parseFloat(await js("document.querySelector('.image-viewer [aria-label=\"Image zoom\"]').textContent")) > 100);
  await capture('large-grid-zoom.png');
  saveName = 'large-grid.png'; await textClick('Save image as…');
  await until("document.querySelector('.image-viewer .image-file-actions')?.textContent.includes('Open saved copy')", 'large original saved');
  const { createHash } = require('node:crypto');
  const hash = createHash('sha256'); for await (const chunk of fs.createReadStream(path.join(work, saveName))) hash.update(chunk);
  assert.equal(hash.digest('hex'), large.sha256);
  saveName = 'large-grid.zip';
  const archive = await js(`window.workstationDesktop.exportLibraryImages([${JSON.stringify(large.id)}])`);
  assert.equal(archive.saved, true);
  assert(archive.size > large.size);
  const signature = Buffer.alloc(2), archiveFile = fs.openSync(path.join(work, saveName), 'r');
  try { fs.readSync(archiveFile, signature, 0, 2, 0); } finally { fs.closeSync(archiveFile); }
  assert.equal(signature.toString(), 'PK');
  await textClick('Fit');
  await win.setSize(640, 900); await capture('large-grid-narrow.png');
  const bounds = await js("(()=>{const s=document.querySelector('.image-zoom-viewport').getBoundingClientRect();return {width:s.width,height:s.height};})()");
  assert(bounds.width > 100 && bounds.height > 100);
  await click('[aria-label="Close image viewer"]');
  await win.setSize(640, 900); await capture('gallery-narrow.png');
  assert.equal(await js('document.documentElement.scrollWidth <= window.innerWidth'), true);
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log(JSON.stringify({ ok: true, checks: ['Nonconsecutive picks from enlarged viewer', 'Selections survive pages, search, collections and collapse', 'Explicit frame reorder and removal', 'Real strip/grid preview and saved PNG', 'Native Save As, open/reveal and byte-identical output', '60-frame 6144px grid: original-resolution zoom, wheel, pan and 108 MiB verified save', 'Narrow viewer fits window; no renderer errors'], artifacts: work }, null, 2));
}).catch(error => { console.error(error); console.error(errors.join('\n')); status = 1; }).finally(() => { clearTimeout(guard); win?.destroy(); backend?.kill(); app.exit(status); });
